import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const conformanceDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.resolve(conformanceDirectory, '../Documentation/renderers/atomic-slot-contracts.md');
const snippetDirectory = path.join(conformanceDirectory, 'for_slot_contracts/snippets');
const regenerateCommand = 'yarn workspace @cratis/components.conformance generate-slot-contracts';

const asCode = (text) => `\`${text}\``;
const bulletList = (items) => items.map((item) => `- ${item}`).join('\n');

const rootElement = (profile) => {
    const native = `${asCode(`<${profile.nativeTag.toLowerCase()}>`)} matching ${asCode(profile.nativeSelector)}`;
    return profile.platformRoot
        ? `${native}, or a platform ${asCode(`<${profile.platformRoot.tag.toLowerCase()}>`)}`
        : native;
};

const partsCell = (profile) => {
    const parts = profile.ptKeys.length > 0 ? profile.ptKeys.map(asCode).join(', ') : 'None in `pt`';
    if (!profile.platformRoot) {
        return parts;
    }
    const owned = profile.platformRoot.ownedParts.map(asCode).join(' and ');
    return `${parts}. A platform ${asCode(`<${profile.platformRoot.tag.toLowerCase()}>`)} owns ${owned}, so those two parts then have no element`;
};

/** Renders the contract table of one slot profile. */
export const renderSlotTable = (profile) =>
    [
        '| Contract | Value |',
        '| --- | --- |',
        `| Props | ${asCode(profile.propsType)} |`,
        `| Root element | ${rootElement(profile)} |`,
        `| Parts | ${partsCell(profile)} |`,
        `| Ref | ${profile.refCapable ? 'Forwards a ref to the root element' : 'None; the slot does not forward a ref'} |`,
    ].join('\n');

const renderSlot = (profile, snippet) =>
    [
        `## ${asCode(profile.slotId)}`,
        '',
        renderSlotTable(profile),
        '',
        'Components owns:',
        '',
        bulletList(profile.ownership.core),
        '',
        'The adapter owns:',
        '',
        bulletList(profile.ownership.adapter),
        '',
        '```tsx',
        snippet.trimEnd(),
        '```',
    ].join('\n');

/**
 * Renders the whole contract page. Slots appear in the order of `slotIds`; a stable slot without a
 * profile, props type, ownership or snippet is an error rather than a silently missing section.
 */
export const renderPage = (profiles, snippets, slotIds) => {
    const sections = slotIds.map((slotId) => {
        const profile = profiles.find((candidate) => candidate.slotId === slotId);
        if (!profile?.propsType || !profile.ownership) {
            throw new Error(`Stable atomic slot ${slotId} has no profile with propsType and ownership.`);
        }
        const snippet = snippets.get(slotId);
        if (!snippet) {
            throw new Error(`Stable atomic slot ${slotId} has no snippet in for_slot_contracts/snippets.`);
        }
        return renderSlot(profile, snippet);
    });
    return [
        '---',
        'title: Atomic slot contracts',
        'description: The props type, root element, parts, ref and Core-versus-adapter ownership of each stable atomic slot an adapter can implement.',
        '---',
        '',
        '<!-- Copyright (c) Cratis. All rights reserved. -->',
        '<!-- Licensed under the MIT license. See LICENSE file in the project root for full license information. -->',
        '',
        `<!-- Generated by Conformance/scripts/generate-slot-contracts.mjs from the conformance slot profiles. Do not edit; change the profile and run \`${regenerateCommand}\`. -->`,
        '',
        'An adapter can implement a stable atomic slot to own the whole interaction of one control. This page',
        'lists, for each slot, the exact props type, the root element, the `pt` parts, whether a ref is',
        'forwarded and which behavior stays in Components. It is generated from the profiles that',
        '`@cratis/components.conformance` runs against a declared slot, so it describes what is tested. See',
        '[Primitive adaptation profile](primitive-adaptation.md#stable-atomic-slots) for how a library',
        'declares an atomic slot.',
        '',
        sections.join('\n\n'),
        '',
    ].join('\n');
};

const readSnippets = (slotIds) =>
    new Map(
        slotIds.map((slotId) => {
            const file = path.join(snippetDirectory, `${slotId.split('.').pop()}.tsx`);
            const source = fs.readFileSync(file, 'utf8');
            return [slotId, source.replace(/^(\/\/.*\n)+\n/, '')];
        }),
    );

const loadInputs = async () => {
    const renderer = await import('@cratis/components/renderer');
    const { createSlotProfiles } = await import(
        pathToFileURL(path.join(conformanceDirectory, 'dist/internal/slotProfiles.js')).href
    );
    const slotIds = [...renderer.cratisAtomicSlotIds];
    return { profiles: createSlotProfiles(new Map()), slotIds, snippets: readSnippets(slotIds) };
};

/** Returns the contract page generated from the built profiles and the compiled snippets. */
export const generatePage = async () => {
    const { profiles, slotIds, snippets } = await loadInputs();
    return { page: renderPage(profiles, snippets, slotIds), count: slotIds.length };
};

/** Compares the committed page with fresh output; returns false when it is stale. */
export const checkPage = (committed, fresh) => committed === fresh;

const main = async () => {
    const mode = process.argv[2] ?? '--check';
    if (!['--check', '--write'].includes(mode)) {
        throw new Error('Usage: node scripts/generate-slot-contracts.mjs [--check|--write]');
    }
    const { page, count } = await generatePage();
    if (mode === '--write') {
        fs.writeFileSync(outputPath, page);
        console.log(`Wrote ${count} atomic slot contracts to ${path.relative(process.cwd(), outputPath)}.`);
        return;
    }
    const committed = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
    if (!checkPage(committed, page)) {
        throw new Error(`The atomic slot contracts page is out of date. Run \`${regenerateCommand}\`.`);
    }
    console.log(`Atomic slot contracts page is current (${count} slots).`);
};

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
    main().catch((error) => {
        console.error(error instanceof Error ? error.message : String(error));
        process.exit(1);
    });
}
