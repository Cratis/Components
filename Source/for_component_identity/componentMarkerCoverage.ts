/**
 * How each public component satisfies the identity-marker rule: its root renders
 * `data-cratis-component="<Name>"`.
 *
 * - `marked`: the source files that declare the marker for the component.
 * - `delegatesTo`: the component renders another marked component as its root.
 * - `exempt`: the component renders no root element of its own; the reason is recorded.
 * - `pending`: not marked yet. This list only shrinks: a pending component that gains the marker
 *   must move to `marked`, and a new component can never be added here.
 */
